async function main() {
  const response = await fetch(`${baseUrl}/api/workflow/projects`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(project),
  });
  const data = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(data.error || `HTTP ${response.status}`);
  process.stdout.write(JSON.stringify({ id: data.project.id, title: data.project.title, duration: data.project.brief.duration, currentStage: data.project.currentStage }));
}

main().catch((error) => { console.error(error.message); process.exitCode = 1; });
